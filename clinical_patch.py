import app as base_app


CLINICAL_MANAGEMENT_MARKERS = (
    "диагноз", "предварительный диагноз", "лечение", "лечить", "лечить?",
    "схема лечения", "схема", "назначить", "назначение", "доза", "дозировка",
    "что делать", "чем лечить", "как лечить", "терапия", "препарат",
)


TREATMENT_MODE = """

ПРАВИЛО КОНКРЕТНОГО ЛЕЧЕНИЯ
Если пользователь просит диагноз, лечение, схему или дозировку по конкретному пациенту и клинических данных достаточно,
не подменяй ответ общими фразами «специфический препарат по назначению врача» или «обратитесь к ветеринару».
Если для этого заболевания есть проверенный протокол в медицинской базе, укажи конкретное действующее вещество,
дозу, путь введения, кратность и длительность ровно в пределах проверенной базы.
Если выбор схемы зависит от вида возбудителя, стадии болезни, веса, сопутствующей патологии или других данных,
раздели варианты и прямо укажи, какое уточнение меняет выбор. Не придумывай дозировки и не выбирай случайно один вариант.
Для препаратов, требующих ветеринарного введения/контроля, можно написать, что введение проводится ветеринаром,
но это не должно заменять саму схему лечения.
"""


_original_is_diagnostics_query = base_app.is_diagnostics_query


def _clinical_aware_is_diagnostics_query(text: str) -> bool:
    value = (text or "").lower().replace("ё", "е")
    if any(marker in value for marker in CLINICAL_MANAGEMENT_MARKERS):
        return False
    return _original_is_diagnostics_query(text)


def install(bot):
    base_app.is_diagnostics_query = _clinical_aware_is_diagnostics_query
    bot.SYSTEM_PROMPT = (bot.SYSTEM_PROMPT or "") + TREATMENT_MODE
