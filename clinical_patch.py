ASSESSMENT_FORMAT_PRIORITY = """

ФОРМАТ ОТВЕТА — МАКСИМАЛЬНЫЙ ПРИОРИТЕТ.
Если пользователь просит конкретную дозировку, сначала дай расчёт дозы. Не заставляй его проходить дополнительный опрос до получения ответа, если исходных данных для расчёта уже достаточно.
В остальных клинических планах читаемость важнее компактности. Не сжимай ответ в плотное полотно.

Если пользователь просит диагноз/лечение/схему, используй разделы по необходимости: предварительный диагноз, основное лечение, поддержка, контроль, дополнительная диагностика. Не добавляй ненужные разделы.

🚨 Стационар / срочно — только при новом конкретном неотложном красном флаге. Если пациент уже осмотрен врачом и обсуждается назначенная операция/лечение, не отправляй владельца заново в клинику без нового основания.
"""


_original_is_diagnostics_query = base_app.is_diagnostics_query
_original_phase_instruction = base_app._phase_instruction


def _clinical_aware_is_diagnostics_query(text: str) -> bool:
    value = (text or "").lower().replace("ё", "е")
    if any(marker in value for marker in CLINICAL_MANAGEMENT_MARKERS):
        return False
    return _original_is_diagnostics_query(text)


def _structured_phase_instruction(decision: dict, budget_requested: bool = False) -> str:
    base = _original_phase_instruction(decision, budget_requested)
    if str(decision.get("stage", "")).upper() == "ASSESSMENT":
        return base + ASSESSMENT_FORMAT_PRIORITY
    return base


def install(bot):
    base_app.is_diagnostics_query = _clinical_aware_is_diagnostics_query
    base_app._phase_instruction = _structured_phase_instruction
    bot.SYSTEM_PROMPT = (bot.SYSTEM_PROMPT or "") + TREATMENT_MODE
