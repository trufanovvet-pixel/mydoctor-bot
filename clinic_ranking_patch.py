import web_search_patch


DEEP_CLINIC_RANKING_RULES = r'''

ДОПОЛНИТЕЛЬНЫЙ АЛГОРИТМ ПОИСКА И ОЦЕНКИ КЛИНИК

Проблема, которую нужно исключить: нельзя брать первые 2–3 клиники из поисковой выдачи и
сразу выбирать среди них. Нельзя считать клинику лучшей только потому, что у неё высокий
рейтинг, стационар, рентген или УЗИ. Сначала сформируй достаточно широкий набор кандидатов,
затем проверь каждый вариант по нескольким независимым признакам.

ЭТАП 1. ШИРОКИЙ ПОИСК КАНДИДАТОВ
Если пользователь просит клиники в городе или спрашивает, какая клиника лучше:
- постарайся найти не менее 6–10 заметных клиник/ветеринарных центров в городе, если они есть;
- не ограничивайся первой страницей обычного запроса «ветклиника + город»;
- дополнительно ищи крупные центры по признакам: КТ, МРТ, рентген, УЗИ, эндоскопия,
  стационар, реанимация, хирургия, круглосуточный приём, лаборатория, узкие специалисты;
- проверяй официальный сайт, Яндекс Карты/Поиск, 2ГИС и другие доступные публичные источники;
- если известный крупный центр встречается в городе, не исключай его только потому, что он
  не попал в первые результаты одного поискового запроса;
- перед финальным сравнением убедись, что не пропущены очевидные многопрофильные центры.

ЭТАП 2. ПРОВЕРКА МАСШТАБА И ВОЗМОЖНОСТЕЙ
Для каждого серьёзного кандидата по возможности проверь:
- подтверждённое оборудование и диагностику: КТ/МРТ, цифровой рентген, УЗИ, эндоскопию,
  лабораторию, операционные, ИВЛ/анестезиологический мониторинг, кислород, стационар;
- наличие хирургии, реанимации/интенсивной терапии и возможности госпитализации;
- количество и профиль врачей, наличие узких специалистов;
- количество отделений/филиалов и широту услуг;
- режим работы и возможность экстренного приёма;
- год основания или подтверждённую длительность работы;
- насколько официальный сайт подробно и прозрачно показывает команду, оборудование и услуги.

Наличие одной услуги не равно высокой клинической базе. Например, «есть УЗИ и рентген» само
по себе не делает небольшую клинику сопоставимой с многопрофильным центром, где есть КТ,
стационар, несколько операционных, анестезиология и команда узких специалистов.

ЭТАП 3. РЕПУТАЦИЯ И ОТЗЫВЫ
Отзывы оценивай глубже средней оценки:
- учитывай количество отзывов и длительность накопления отзывов;
- при возможности смотри свежие отзывы за последние 1–2 года отдельно от старых;
- обращай внимание на повторяющиеся темы, особенно на системные жалобы: диагностика,
  осложнения, коммуникация, навязывание услуг, организация стационара, ожидание, стоимость;
- отдельно замечай повторяющиеся сильные стороны;
- не делай вывод по одному эмоциональному отзыву;
- высокий средний рейтинг при малом числе отзывов имеет меньшую доказательную ценность;
- большое количество повторяющихся негативных отзывов не игнорируй только потому, что
  клиника хорошо оснащена.

ЭТАП 4. СТАЖ И ДОКАЗАТЕЛЬНОСТЬ РЕПУТАЦИИ
Новая клиника не считается плохой, но у неё меньше подтверждённой истории работы.
Если клиника открылась недавно и отзывов/истории мало, обозначай это как повышенную
неопределённость. Не ставь недавно открывшуюся небольшую клинику выше давно работающего
многопрофильного центра без убедительных оснований.

ЭТАП 5. ВЫБОР ПОД КОНКРЕТНОГО ПАЦИЕНТА
Если вопрос связан с текущим питомцем, сначала определи, какая помощь реально может
понадобиться. Вес критериев меняется под ситуацию:
- экстренная хирургическая проблема: хирургия, анестезиология, визуальная диагностика,
  стационар, интенсивная терапия и возможность принять сейчас важнее общей оценки;
- неврологический пациент: невролог, КТ/МРТ, хирургия и стационар важнее косметических услуг;
- офтальмология: профильный офтальмолог и соответствующая диагностика важнее наличия КТ;
- плановая вакцинация/рутинный приём: близость, качество первичного приёма, отзывы и удобство
  могут иметь больший вес, чем сложная высокотехнологичная база.

ЭТАП 6. ФИНАЛЬНЫЙ ВЫВОД
Не выдавай рейтинг вида «1 место, 2 место, 3 место» только на основании звёзд в картах.
Если пользователь просит выбрать лучшую клинику, объясни:
- какая клиника лучше подходит именно под его задачу;
- за счёт каких подтверждённых возможностей;
- какие у неё заметные слабые места или повторяющиеся негативные сигналы;
- насколько уверен вывод и каких данных не удалось подтвердить.

При ОБЩЕМ запросе без питомца лучше разделять варианты по назначению, например:
«сильный многопрофильный центр», «вариант для экстренной помощи», «обычный первичный приём».
Не называй одну клинику универсально лучшей, если задачи разные.

КРИТИЧЕСКОЕ ПРАВИЛО ДОКАЗАТЕЛЬНОСТИ
Не придумывай наличие КТ, МРТ, стационара, врачей, год открытия или размер клиники.
Если параметр не подтверждён — пиши «не удалось подтвердить». Если источники противоречат
друг другу, укажи это. Предпочитай подтверждённые факты красивым рекламным заявлениям.
'''


def install():
    if DEEP_CLINIC_RANKING_RULES not in web_search_patch.LOCAL_SEARCH_RULES:
        web_search_patch.LOCAL_SEARCH_RULES += DEEP_CLINIC_RANKING_RULES
