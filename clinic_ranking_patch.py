import web_search_patch


DEEP_CLINIC_RANKING_RULES = r'''

ДОПОЛНИТЕЛЬНЫЙ АЛГОРИТМ ПОИСКА И ОЦЕНКИ КЛИНИК

Главная цель: при обычном запросе «посоветуй хорошую ветеринарную клинику» искать в первую
очередь полноценные ветеринарные центры, способные провести диагностику и лечение сложного
пациента. Не заполняй рекомендации маленькими кабинетами только потому, что у них высокий
рейтинг или они стоят выше в поисковой выдаче.

ЭТАП 1. ШИРОКИЙ ПОИСК КАНДИДАТОВ
Если пользователь просит клиники в городе или спрашивает, какая клиника лучше:
- сначала постарайся обнаружить 6–10 заметных клиник/ветеринарных центров, если они есть;
- не ограничивайся первыми результатами запроса «ветклиника + город»;
- отдельно ищи крупные центры по сочетаниям: стационар, хирургия, анестезиология,
  рентген, УЗИ, КТ/МРТ, эндоскопия, лаборатория, реанимация, узкие специалисты;
- проверяй официальный сайт, Яндекс Карты/Поиск, 2ГИС и другие доступные источники;
- перед финальным ответом убедись, что не пропущены очевидные многопрофильные центры.

ЭТАП 2. ЖЁСТКИЙ ФИЛЬТР МАСШТАБА
Для общего запроса «хорошая/лучшая клиника» основная выборка должна состоять из полноценных
ветеринарных центров. В приоритете учреждения, где подтверждается несколько независимых
признаков серьёзной клинической базы:
- хирургия и полноценная операционная;
- анестезиологическое обеспечение и мониторинг;
- стационар/госпитализация;
- визуальная диагностика: рентген и УЗИ, а при наличии КТ/МРТ/эндоскопия;
- собственная или развитая лабораторная диагностика;
- несколько врачей и узкие специалисты;
- возможность вести сложного пациента от диагностики до лечения в одном месте;
- экстренный или расширенный режим работы.

Не включай в основной список небольшие кабинеты, одиночные врачебные практики, пункты
вакцинации, груминг-центры с ветеринарным кабинетом и маленькие клиники с очень ограниченной
диагностикой, ЕСЛИ в городе есть более полноценные центры.

Исключение: пользователь сам просит ближайший кабинет, вакцинацию, чипирование, простую
процедуру или в городе объективно нет крупных центров. Тогда небольшой вариант допустим,
но прямо обозначь ограниченность его возможностей.

Если пользователь просит, например, «5 лучших клиник», а критериям полноценного центра
соответствуют только 2–3 учреждения, верни 2–3. НЕ добивай список до нужного количества
слабыми вариантами ради числа.

ЭТАП 3. ПРОВЕРКА ВОЗМОЖНОСТЕЙ
Для серьёзных кандидатов по возможности проверь:
- подтверждённое оборудование и диагностику: КТ/МРТ, цифровой рентген, УЗИ, эндоскопию,
  лабораторию, операционные, ИВЛ/анестезиологический мониторинг, кислород;
- стационар, интенсивную терапию и возможность госпитализации;
- профиль и размер врачебной команды, наличие узких специалистов;
- количество отделений/филиалов и широту услуг;
- режим работы и возможность экстренного приёма;
- год основания или подтверждённую длительность работы;
- насколько официальный сайт прозрачно показывает команду, оборудование и услуги.

Наличие одной услуги не равно сильной клинической базе. «Есть УЗИ и рентген» само по себе
не делает небольшую клинику сопоставимой с многопрофильным центром, где есть стационар,
операционная, анестезиология, сложная визуальная диагностика и команда специалистов.

ЭТАП 4. ОТЗЫВЫ — НИЗКИЙ ПОЛОЖИТЕЛЬНЫЙ ВЕС, НО ВАЖНЫЙ СИГНАЛ РИСКА
Отзывы и средняя звезда НЕ должны продвигать клинику вверх сильнее клинической базы.
Высокий рейтинг используй максимум как слабый дополнительный аргумент между клиниками
сопоставимого уровня.

При этом негативные отзывы анализируй как возможный сигнал риска:
- учитывай количество отзывов и длительность их накопления;
- при возможности отдельно смотри свежие отзывы последних 1–2 лет;
- обращай внимание только на повторяющиеся темы, а не на одиночные эмоциональные отзывы;
- особенно важны повторяющиеся жалобы на ошибки диагностики, осложнения, стационар,
  послеоперационное наблюдение, коммуникацию, организацию лечения и навязывание услуг;
- если серьёзные негативные темы повторяются в большом числе независимых отзывов,
  заметно снижай уверенность в рекомендации даже при хорошем оснащении;
- высокая средняя оценка при малом количестве отзывов почти ничего не доказывает;
- количество отзывов используй прежде всего как показатель надёжности выборки, а не качества.

ЭТАП 5. СТАЖ И УСТОЙЧИВОСТЬ
Новая клиника не считается плохой, но у неё меньше подтверждённой истории работы.
Не ставь недавно открывшуюся маленькую клинику выше давно работающего многопрофильного
центра без сильных подтверждённых оснований. Короткая история работы = меньшая уверенность,
а не автоматический минус.

ЭТАП 6. ВЫБОР ПОД КОНКРЕТНОГО ПАЦИЕНТА
Если вопрос связан с текущим питомцем, сначала определи, какая помощь реально может
понадобиться. Вес критериев меняется под ситуацию:
- экстренная хирургия: хирургия, анестезиология, визуальная диагностика, стационар,
  интенсивная терапия и возможность принять сейчас;
- неврология: невролог, КТ/МРТ, хирургия и стационар;
- офтальмология: профильный офтальмолог и соответствующая диагностика;
- тяжёлый неясный пациент: многопрофильный центр с широкой диагностической базой;
- вакцинация/простая процедура: тогда допустимы более небольшие клиники, если это удобно.

ЭТАП 7. ФИНАЛЬНЫЙ ОТВЕТ
При общем запросе без питомца по умолчанию рекомендуй именно крупные/многопрофильные
центры, а не «самые высокооценённые точки на карте».

Если пользователь просит выбрать лучшую клинику, объясни кратко:
- почему она относится к полноценному центру;
- какие диагностические и лечебные возможности подтверждены;
- какие значимые слабые места или повторяющиеся негативные сигналы обнаружены;
- насколько уверен вывод и чего не удалось подтвердить.

Не выдавай клинику как сильный центр только из-за красивого сайта, рейтинга 5.0,
нового ремонта или наличия одного аппарата.

КРИТИЧЕСКОЕ ПРАВИЛО ДОКАЗАТЕЛЬНОСТИ
Не придумывай наличие КТ, МРТ, стационара, врачей, год открытия или размер клиники.
Если параметр не подтверждён — пиши «не удалось подтвердить». Если источники противоречат
друг другу, укажи это. Предпочитай подтверждённые факты рекламным заявлениям.

ЕСТЕСТВЕННЫЙ ЗАПРОС ПОЛЬЗОВАТЕЛЯ
Пользователь не обязан перечислять критерии. Фразы вроде «посоветуй хорошую клинику
в Туле», «найди 5 лучших клиник», «куда лучше обратиться» должны автоматически запускать
весь алгоритм. Не перекладывай методику поиска на пользователя.
'''


NATURAL_LOCAL_TERMS = (
    "клиник",
    "ветеринар",
    "ветцентр",
    "вет центр",
)

NATURAL_SEARCH_TERMS = (
    "хорош",
    "лучш",
    "нормальн",
    "посовет",
    "порекомендуй",
    "порекомендуйте",
    "напиши мне",
    "подскажи",
    "выбери",
    "куда обратиться",
    "куда поехать",
    "куда ехать",
)


def install():
    if DEEP_CLINIC_RANKING_RULES not in web_search_patch.LOCAL_SEARCH_RULES:
        web_search_patch.LOCAL_SEARCH_RULES += DEEP_CLINIC_RANKING_RULES

    for term in NATURAL_LOCAL_TERMS:
        if term not in web_search_patch.LOCAL_TERMS:
            web_search_patch.LOCAL_TERMS += (term,)

    for term in NATURAL_SEARCH_TERMS:
        if term not in web_search_patch.SEARCH_TERMS:
            web_search_patch.SEARCH_TERMS += (term,)
