def owner_messages(messages):
    return [m for m in messages if isinstance(m, dict) and m.get('role') == 'user'] if isinstance(messages, list) else messages


def controller_input(messages):
    """Keep previous questions for short answers, never promote AI assertions."""
    import re
    result = []
    for m in messages if isinstance(messages, list) else []:
        if not isinstance(m, dict):
            continue
        if m.get('role') == 'user':
            result.append(m)
        elif m.get('role') == 'assistant' and isinstance(m.get('content'), str):
            questions = re.findall(r'[^.!?\n]+\?', m['content'])
            if questions:
                result.append({'role': 'developer', 'content':
                    'Предыдущие вопросы помощника (НЕ факты пациента): ' + ' '.join(questions)})
    return result
